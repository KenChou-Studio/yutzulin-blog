#!/usr/bin/env node
/**
 * Generates src/plugins/blocks-admin.generated.css from the site's real styles
 * so custom blocks look the same in the admin editor and in on-page visual
 * editing as they do on the public site.
 *
 *   node scripts/sync-block-css.mjs
 *
 * Inputs : design tokens (tokens.css + theme.css), global .btn/.eyebrow/.chip
 *          rules from Base.astro, and the <style> of each block component.
 * Output : the same rules scoped under `.sb-node`, the wrapper the editor
 *          node views render into.
 */
import { readFileSync, writeFileSync } from "node:fs";
import postcss from "postcss";

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), "utf8");
const styleBlocks = (source) =>
	[...source.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]);

const COMPONENTS = [
	"Callout",
	"InfoCard",
	"CardGrid",
	"ContactItem",
	"ContactList",
	"HeroBlock",
	"StatsBlock",
	"RecentPostsBlock",
	"RecentNewsBlock",
	"VideoEmbed",
	"NewsItem",
	"NewsGrid",
].map((name) => `src/components/ui/${name}.astro`);

const scope = (selector) =>
	selector
		.replace(/:global\(([^)]*)\)/g, "$1")
		.trim()
		.replace(/^/, ".sb-node ");

function scoped(css, keep = () => true) {
	const root = postcss.parse(css);
	root.walkRules((rule) => {
		if (rule.parent?.type === "atrule" && /keyframes/.test(rule.parent.name)) return;
		rule.selectors = rule.selectors.map(scope);
	});
	root.walkAtRules("layer", (at) => at.replaceWith(at.nodes ?? []));
	root.walkRules((rule) => {
		if (!keep(rule)) rule.remove();
	});
	root.walkAtRules((at) => {
		if (at.nodes && at.nodes.length === 0) at.remove();
	});
	root.walkComments((c) => c.remove());
	return root.toString();
}

function declsOf(css, test) {
	const out = [];
	postcss.parse(css).walkRules((rule) => {
		if (rule.parent?.type === "atrule" && rule.parent.name !== "layer") return;
		if (!test(rule.selector)) return;
		rule.each((d) => {
			if (d.type === "decl") out.push(`${d.prop}: ${d.value};`);
		});
	});
	return out;
}

const tokens = read("src/styles/tokens.css");
const theme = read("src/styles/theme.css");
const lightDecls = [
	...declsOf(tokens, (s) => s.trim() === ":root"),
	...declsOf(theme, (s) => s.trim() === ":root"),
].filter((d) => !d.startsWith("color-scheme"));
const darkDecls = declsOf(theme, (s) => s.includes('[class~="dark"]'));

const baseStyles = styleBlocks(read("src/layouts/Base.astro")).join("\n");
const globals = scoped(baseStyles, (rule) =>
	rule.selectors.every((s) => /^\.sb-node \.(btn|eyebrow|chip)\b/.test(s)),
);

const components = COMPONENTS.map((file) => `/* ${file} */\n${scoped(styleBlocks(read(file)).join("\n"))}`).join("\n");

const header = `/* GENERATED by scripts/sync-block-css.mjs — do not edit by hand. */\n`;
const body = `
.sb-node {
	color-scheme: light;
	${lightDecls.join("\n\t")}
	--font-body: system-ui, -apple-system, "Segoe UI", "Noto Sans TC", sans-serif;
	--font-heading: var(--font-body);
	--font-mono: ui-monospace, "JetBrains Mono", Menlo, monospace;
	font-family: var(--font-body);
	color: var(--color-text);
	line-height: 1.5;
}
:is(.dark, [data-mode="dark"]) .sb-node {
	color-scheme: dark;
	${darkDecls.join("\n\t")}
}
${globals}
${components}
`;
writeFileSync(new URL("../src/plugins/blocks-admin.generated.css", import.meta.url), header + body);
console.log("wrote src/plugins/blocks-admin.generated.css", (header + body).length, "bytes");
